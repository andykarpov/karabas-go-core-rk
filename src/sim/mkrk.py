#!/usr/bin/env python3
# A test tape file for run_boot.sh: at 0100 it writes 5A at 1000 and stops in a loop. The RK format:
# E6, start and end (high byte first), the bytes, a checksum.
#   mkrk.py OUT          the test above
#   mkrk.py OUT sdwrite  a block written through the SD adapter of SDOS (see below)
#   mkrk.py OUT mkbeep   a tone of 1 kHz on the 8253 of the Mikrosha
#   mkrk.py OUT ramdisk  the RAM disk of the Mikro-80: page 1 (OUT 40, FE), PUSH A55A at 1000, the main
#                        memory again (OUT 40, FF), a loop: A5 5A in page 1 at 1000, nothing at 1000
import sys
if len(sys.argv) > 2 and sys.argv[2] == 'sdwrite':
    # the SD adapter of SDOS (D000 data, D001 select): CMD24 of LBA 0FFF (the last sector of a 2 MB image),
    # the bytes 00..FF twice, wait for the end of the write; then 5A at 1000 and a loop
    code = bytes([0x3E, 0x01, 0x32, 0x01, 0xD0,                     # 0100 select
                  0x21, 0x50, 0x01, 0x06, 0x06,                     # 0105 the command, 6 bytes
                  0x7E, 0x32, 0x00, 0xD0, 0x23, 0x05, 0xC2, 0x0A, 0x01,
                  0x3E, 0xFF, 0x32, 0x00, 0xD0,                     # 0113 R1
                  0x3E, 0xFE, 0x32, 0x00, 0xD0,                     # 0118 the token
                  0x0E, 0x00, 0x16, 0x02,                           # 011D 512 bytes
                  0x79, 0x32, 0x00, 0xD0, 0x0C, 0xC2, 0x21, 0x01, 0x15, 0xC2, 0x21, 0x01,
                  0x3E, 0xFF, 0x32, 0x00, 0xD0, 0x3E, 0xFF, 0x32, 0x00, 0xD0,   # 012D the CRC
                  0x3E, 0xFF, 0x32, 0x00, 0xD0, 0x3A, 0x00, 0xD0, 0xFE, 0xFF, 0xC2, 0x37, 0x01,  # 0137 until FF
                  0xAF, 0x32, 0x01, 0xD0,                           # 0144 deselect
                  0x3E, 0x5A, 0x32, 0x00, 0x10, 0xC3, 0x4D, 0x01,   # 0148
                  0x58, 0x00, 0x00, 0x0F, 0xFF, 0xFF])              # 0150 CMD24
elif len(sys.argv) > 2 and sys.argv[2] == 'mkbeep':
    # the Mikrosha: 8253 channel 2 (D800), mode 3, count 1777 = 1000 Hz; PC2 its gate, PC1 the sound (C003)
    code = bytes([0x3E, 0xB6, 0x32, 0x03, 0xD8, 0x3E, 0xF1, 0x32, 0x02, 0xD8, 0x3E, 0x06, 0x32, 0x02, 0xD8,
                  0x3E, 0x05, 0x32, 0x03, 0xC0, 0x3E, 0x03, 0x32, 0x03, 0xC0,
                  0x3E, 0x5A, 0x32, 0x00, 0x10, 0xC3, 0x1E, 0x01])
elif len(sys.argv) > 2 and sys.argv[2] == 'ramdisk':
    code = bytes([0x3E, 0xFE, 0xD3, 0x40, 0x31, 0x02, 0x10, 0x01, 0x5A, 0xA5, 0xC5,
                  0x3E, 0xFF, 0xD3, 0x40, 0xC3, 0x0F, 0x01])
else:
    code = bytes([0x3E, 0x5A, 0x32, 0x00, 0x10, 0xC3, 0x05, 0x01])
start = 0x0100
end = start + len(code) - 1
cs = sum(code) & 0xFFFF
open(sys.argv[1], 'wb').write(bytes([0xE6]) + start.to_bytes(2, 'big') + end.to_bytes(2, 'big') + code + cs.to_bytes(2, 'big'))
